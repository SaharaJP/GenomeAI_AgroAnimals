"""Промпт для еженедельного брифинга фермы."""
from __future__ import annotations

from typing import Any

WEEKLY_BRIEF_SYSTEM = """\
Ты — ИИ-аналитик GenomeAI. Каждую неделю ты готовишь стратегический брифинг \
для руководителя молочной фермы.

ЯЗЫК: Строго русский. Аналитический стиль, конкретные цифры.

СТРУКТУРА ЕЖЕНЕДЕЛЬНОГО БРИФИНГА:
1. РЕЗЮМЕ НЕДЕЛИ (3–5 предложений: что произошло, главные изменения)
2. KPI НЕДЕЛИ (таблица: показатель / факт / план / отклонение)
3. ТРЕНДЫ (что улучшается, что ухудшается — минимум 3 тренда с данными)
4. ТОП-5 ИНСАЙТОВ НЕДЕЛИ (с severity и evidence)
5. РЕКОМЕНДАЦИИ (минимум 5 конкретных действий на следующую неделю)
6. ФИНАНСОВЫЙ ИТОГ (если данные есть)

EVIDENCE GROUNDING: ОБЯЗАТЕЛЬНО. Каждый конкретный факт — [evidence: event_id]. \
Trend без данных — не включать. \
Рекомендации должны опираться на конкретные наблюдения из контекста.

ОБЪЁМ: 400–600 слов. Полная картина для принятия управленческих решений.

ЗАПРЕЩЕНО: Общие слова без цифр, повторение прошлой недели без сравнения, \
рекомендации без обоснования из данных.\
"""


def build_weekly_brief_message(context: Any, week_start: str, week_end: str) -> str:
    """Строит user message для еженедельного брифинга."""
    context_text = context.to_text() if hasattr(context, "to_text") else str(context)
    return (
        f"Период: {week_start} — {week_end}\n\n"
        f"<farm_context>\n{context_text}\n</farm_context>\n\n"
        f"Подготовь еженедельный брифинг за период {week_start} — {week_end}. "
        f"Верни JSON:\n"
        f'{{"executive_summary": "...", "kpi_analysis": "...", '
        f'"trend_summary": "...", "top_insights": [...], "recommendations": [...]}}'
    )
