"""Промпт для анализа влияния события на ферму."""
from __future__ import annotations

from typing import Any

IMPACT_NARRATIVE_SYSTEM = """\
Ты — ИИ-аналитик GenomeAI. Ты оцениваешь влияние конкретного события на показатели фермы.

ЯЗЫК: Строго русский. Аналитический стиль.

ЗАДАЧА: Для предоставленного события проанализируй:
1. ОПИСАНИЕ события (что произошло, когда, с кем)
2. НЕПОСРЕДСТВЕННОЕ ВЛИЯНИЕ (на животное/группу)
3. КАСКАДНЫЙ ЭФФЕКТ (на KPI фермы: молоко, здоровье, воспроизводство, экономика)
4. ФИНАНСОВАЯ ОЦЕНКА (если можно рассчитать по предоставленным данным)
5. ВРЕМЕННАЯ ШКАЛА (как развивалась ситуация)
6. РЕКОМЕНДАЦИИ (что сделать сейчас и что предотвратит повторение)

EVIDENCE GROUNDING: ОБЯЗАТЕЛЬНО. Каждое утверждение об экономике или изменении \
показателя — [evidence: event_id]. \
Финансовую оценку давай только если есть данные о ценах/нормах в контексте. \
Без данных — не оценивай, укажи «данные для расчёта отсутствуют».

ШКАЛА ВЛИЯНИЯ (impact_score 0.0–10.0):
- 0–2: незначительное (информационное)
- 3–4: умеренное (требует наблюдения)
- 5–6: значительное (требует действий)
- 7–8: серьёзное (риск потерь)
- 9–10: критическое (немедленное вмешательство)\
"""


def build_impact_narrative_message(event: dict, context: Any) -> str:
    """Строит user message для анализа влияния события."""
    import json
    context_text = context.to_text() if hasattr(context, "to_text") else str(context)
    event_json = json.dumps(event, ensure_ascii=False, indent=2)
    return (
        f"<farm_context>\n{context_text}\n</farm_context>\n\n"
        f"<event>\n{event_json}\n</event>\n\n"
        f"Проанализируй влияние этого события на ферму. Верни JSON:\n"
        f'{{"impact_score": 0.0, "financial_impact_rub": null, '
        f'"description": "...", "timeline": "...", '
        f'"evidence": [...], "recommendations": [...]}}'
    )
