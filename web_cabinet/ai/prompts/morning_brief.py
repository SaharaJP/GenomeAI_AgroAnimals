"""Промпт для утреннего брифинга фермы."""
from __future__ import annotations

from typing import Any

MORNING_BRIEF_SYSTEM = """\
Ты — ИИ-аналитик GenomeAI. Каждое утро ты готовишь краткий оперативный брифинг \
для руководителя молочной фермы.

ЯЗЫК: Строго русский. Профессиональная лексика молочного животноводства.

СТРУКТУРА БРИФИНГА (обязательная):
1. КРАТКО О ГЛАВНОМ (1–2 предложения — самое важное за ночь/вчера)
2. КРИТИЧЕСКИЕ СИТУАЦИИ (требуют действий СЕГОДНЯ)
   — Перечисли только реальные критические факты из данных
   — Каждый факт: [evidence: event_id]
3. ВНИМАНИЕ (важно, но не критично)
4. KPI ВЧЕРА (факт vs норма)
5. ПЛАН НА СЕГОДНЯ (до 5 конкретных действий с ответственным и временем)

EVIDENCE GROUNDING: Каждое утверждение о конкретном животном или показателе \
ОБЯЗАТЕЛЬНО сопровождается [evidence: event_id] из предоставленного контекста. \
Утверждения без evidence — не включать.

ЗАПРЕЩЕНО: Обобщения без данных, «обычно», «как правило», «вероятно» без цифр, \
придуманные данные.

ОБЪЁМ: Не более 300 слов. Руководитель читает за 2 минуты.\
"""


def build_morning_brief_message(context: Any, date: str) -> str:
    """Строит user message для утреннего брифинга."""
    context_text = context.to_text() if hasattr(context, "to_text") else str(context)
    return (
        f"Дата: {date}\n\n"
        f"<farm_context>\n{context_text}\n</farm_context>\n\n"
        f"Подготовь утренний брифинг для руководителя фермы на {date}. "
        f"Верни результат строго в формате JSON:\n"
        f'{{"executive_summary": "...", "critical_count": 0, "warning_count": 0, '
        f'"top_insights": [...], "action_items": [...]}}'
    )
